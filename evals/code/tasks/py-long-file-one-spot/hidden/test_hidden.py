class DurationTest(unittest.TestCase):
    def test_under_an_hour_as_before(self):
        for seconds, text in [(0, "0s"), (45, "45s"), (59, "59s"), (60, "1m"), (90, "1m 30s"),
                              (300, "5m"), (3599, "59m 59s")]:
            self.assertEqual(textfmt.format_duration(seconds), text)

    def test_from_an_hour_up(self):
        for seconds, text in [(3600, "1h"), (3601, "1h"), (3660, "1h 1m"), (5400, "1h 30m"),
                              (7200, "2h"), (7259, "2h"), (86400, "24h"), (90000, "25h"), (-3600, "-1h"), (-5400, "-1h 30m")]:
            self.assertEqual(textfmt.format_duration(seconds), text)

    def test_the_callers_follow(self):
        self.assertEqual(textfmt.format_uptime(5400), "up 1h 30m")
        self.assertEqual(textfmt.format_uptime(-5), "up 0s")
        self.assertEqual(textfmt.format_eta(7200), "about 2h")
        self.assertEqual(textfmt.format_eta(59), "less than a minute")
        self.assertEqual(textfmt.format_eta(90), "about 1m 30s")
        self.assertEqual(status.render(3 * 3600 + 60, 1, 2, 5 * 1024 ** 3, 3900),
                         "up 3h 1m\njobs 1 of 2 (50%)\ndisk 5 GB\nnext run about 1h 5m")

    def test_the_docstring_keeps_up(self):
        self.assertIn("hour", textfmt.format_duration.__doc__.lower())


